export interface Resource {
  readonly locale: string;
  readonly chrome: Chrome;
  readonly words: Readonly<Partial<Record<string, readonly string[]>>>;
}

export interface LanguageOption {
  readonly tag: string;
  readonly name: string;
}

export const LANGUAGES: readonly LanguageOption[] = [{ tag: 'en', name: 'English' }];

const STORAGE_KEY = 'language';
const HOLE = /\{([^}|]+)(?:\|([^}|]*)\|([^}]*))?\}/g;

let language = '';
let resource: Resource | null = null;
const listeners = new Set<() => void>();

function loaded(): Resource {
  if (resource === null) {
    throw new Error('No language is loaded');
  }
  return resource;
}

async function resourceOf(tag: string): Promise<Resource> {
  switch (tag) {
    case 'en':
      return (await import('./en')).default;
    default:
      throw new Error(`No resource for language '${tag}'`);
  }
}

function baseLanguage(tag: string): string {
  return tag.split('-')[0] ?? tag;
}

function offeredLanguage(tag: string | null): string | null {
  if (tag === null) {
    return null;
  }
  return LANGUAGES.find((option) => baseLanguage(option.tag) === baseLanguage(tag))?.tag ?? null;
}

function storedLanguage(): string | null {
  try {
    return offeredLanguage(window.localStorage.getItem(STORAGE_KEY));
  } catch {
    return null;
  }
}

export function initialLanguage(): string {
  const first = LANGUAGES.at(0);
  if (first === undefined) {
    throw new Error('The system offers at least one language');
  }
  return storedLanguage() ?? first.tag;
}

export async function setLanguage(tag: string): Promise<void> {
  resource = await resourceOf(tag);
  language = tag;
  document.documentElement.lang = tag;
  try {
    window.localStorage.setItem(STORAGE_KEY, tag);
  } catch {
    /* Empty by design */
  }
  for (const listener of listeners) {
    listener();
  }
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return (): void => {
    listeners.delete(listener);
  };
}

export function useLanguage(): string {
  return useSyncExternalStore(subscribe, () => language);
}

export const i18n = {
  get language(): string {
    return language;
  },
  get locale(): string {
    return loaded().locale;
  },
  get chrome(): Chrome {
    return loaded().chrome;
  },
  word(key: string, form = 0): string {
    const word = loaded().words[key]?.at(form);
    if (word === undefined) {
      throw new Error(`No word for '${key}' in '${language}'`);
    }
    return word;
  },
  fill(template: string, values: Readonly<Partial<Record<string, string | number>>>): string {
    return template.replace(HOLE, (_match, hole: string, one?: string, many?: string) => {
      const value = values[hole];
      if (value === undefined) {
        throw new Error(`The template '${template}' names a hole '${hole}' without a value`);
      }
      if (one === undefined || many === undefined) {
        return String(value);
      }
      return Number(value) === 1 ? one : many;
    });
  },
};
